export function resolveYearStories(catalog:YearCatalog) {
  const items=new Map(catalog.items.filter(item=>!item.deleted).map(item=>[item.id,item]));
  return YEAR_STORIES.map(story=>({...story,stops:story.stops.flatMap(stop=>{
    const item=items.get(stop.itemId);
    // Hide a stale annotation if a future catalogue changes the date for this ID.
    return item&&comparableYear(item.year)===stop.year?[{item,connection:stop.connection}]:[];
  }).sort((a,b)=>comparableYear(a.item.year)!-comparableYear(b.item.year)!)}));
}
